import 'package:flutter/material.dart';
import 'package:easy_localization/easy_localization.dart';
import 'package:shared_preferences/shared_preferences.dart';

import '../../services/api_service.dart';

import 'order_medicines_page.dart';

class MedicineOrdersPage extends StatefulWidget {
  const MedicineOrdersPage({super.key});

  @override
  State<MedicineOrdersPage> createState() =>
      _MedicineOrdersPageState();
}

class _MedicineOrdersPageState extends State<MedicineOrdersPage> {
  // ============================================================
  // COLORS
  // ============================================================

  static const Color primaryColor = Color(0xff00C2CB);

  static const Color backgroundColor = Color(0xffF7F8FA);

  static const Color darkText = Color(0xff0F172A);

  // ============================================================
  // VARIABLES
  // ============================================================

  bool isLoading = true;

  List<dynamic> orders = [];

  String patientPhone = "";

  // ============================================================
  // DELIVERY OTP STORAGE
  //
  // This stores the OTP only in Flutter memory.
  //
  // Backend demo endpoint:
  // GET /api/orders/delivery-otp/:id
  //
  // Key   = orderId
  // Value = OTP
  // ============================================================

  final Map<String, String> deliveryOtps = {};

  // Stores OTP loading state for each order.
  final Set<String> loadingOtpOrders = {};

  // Stores OTP error message for each order.
  final Map<String, String> otpErrors = {};

  // ============================================================
  // INIT
  // ============================================================

  @override
  void initState() {
    super.initState();

    loadOrders();
  }

  // ============================================================
  // LOAD ORDERS
  // ============================================================

  Future<void> loadOrders() async {
    try {
      if (mounted) {
        setState(() {
          isLoading = true;
        });
      }

      final prefs = await SharedPreferences.getInstance();

      patientPhone =
          prefs.getString("patientPhone") ??
          prefs.getString("userPhone") ??
          "";

      if (patientPhone.isEmpty) {
        throw Exception(
          "patientPhoneNumberNotFound".tr(),
        );
      }

      debugPrint(
        "========================================",
      );

      debugPrint(
        "LOADING PATIENT MEDICINE ORDERS",
      );

      debugPrint(
        "PATIENT PHONE = $patientPhone",
      );

      debugPrint(
        "========================================",
      );

      final data =
          await ApiService.getPatientMedicineOrders(
        patientPhone,
      );

      debugPrint(
        "PATIENT MEDICINE ORDERS = $data",
      );

      if (!mounted) return;

      setState(() {
        orders = data;

        isLoading = false;
      });

      // ========================================================
      // LOAD DELIVERY OTPs
      // ========================================================

      await loadDeliveryOtps();
    } catch (e) {
      debugPrint(
        "LOAD MEDICINE ORDERS ERROR = $e",
      );

      if (!mounted) return;

      setState(() {
        isLoading = false;
      });

      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text(
            "${"unableToLoadOrders".tr()}: $e",
          ),
          backgroundColor: Colors.red,
        ),
      );
    }
  }

  // ============================================================
  // LOAD DELIVERY OTPs
  //
  // For every Out for Delivery order:
  //
  // GET /api/orders/delivery-otp/:id
  //
  // This gets the same OTP generated by backend.
  // ============================================================

  Future<void> loadDeliveryOtps() async {
    if (orders.isEmpty) {
      return;
    }

    debugPrint(
      "========================================",
    );

    debugPrint(
      "LOADING DELIVERY OTPs",
    );

    debugPrint(
      "========================================",
    );

    for (final rawOrder in orders) {
      try {
        final order =
            Map<String, dynamic>.from(rawOrder);

        final orderId =
            order["_id"]?.toString() ??
            order["id"]?.toString() ??
            "";

        final status =
            order["status"]?.toString() ??
            "";

        // ------------------------------------------------------
        // Skip orders without ID.
        // ------------------------------------------------------

        if (orderId.isEmpty) {
          continue;
        }

        // ------------------------------------------------------
        // Only Out for Delivery needs OTP.
        // ------------------------------------------------------

        if (!isOutForDelivery(status)) {
          continue;
        }

        await fetchDeliveryOtp(orderId);
      } catch (e) {
        debugPrint(
          "DELIVERY OTP LOOP ERROR = $e",
        );
      }
    }
  }

  // ============================================================
  // FETCH ONE DELIVERY OTP
  // ============================================================

  Future<void> fetchDeliveryOtp(
    String orderId,
  ) async {
    if (orderId.isEmpty) {
      return;
    }

    // Prevent duplicate request.
    if (loadingOtpOrders.contains(orderId)) {
      return;
    }

    if (mounted) {
      setState(() {
        loadingOtpOrders.add(orderId);

        otpErrors.remove(orderId);
      });
    }

    try {
      debugPrint(
        "========================================",
      );

      debugPrint(
        "GETTING DELIVERY OTP",
      );

      debugPrint(
        "ORDER ID = $orderId",
      );

      debugPrint(
        "========================================",
      );

      final result =
          await ApiService.getDeliveryOtp(
        orderId: orderId,
      );

      debugPrint(
        "DELIVERY OTP RESULT = $result",
      );

      final success =
          result["success"] == true;

      if (success) {
        final otp =
            result["deliveryOtp"]?.toString().trim() ??
            "";

        if (otp.isNotEmpty) {
          if (!mounted) return;

          setState(() {
            deliveryOtps[orderId] = otp;

            otpErrors.remove(orderId);
          });

          debugPrint(
            "DELIVERY OTP LOADED = $otp",
          );
        } else {
          if (!mounted) return;

          setState(() {
            otpErrors[orderId] =
                "OTP was not returned by server.";
          });
        }
      } else {
        final message =
            result["message"]?.toString() ??
            "Unable to get delivery OTP.";

        if (!mounted) return;

        setState(() {
          otpErrors[orderId] = message;
        });

        debugPrint(
          "DELIVERY OTP ERROR = $message",
        );
      }
    } catch (e) {
      debugPrint(
        "FETCH DELIVERY OTP ERROR = $e",
      );

      if (!mounted) return;

      setState(() {
        otpErrors[orderId] =
            e.toString();
      });
    } finally {
      if (!mounted) return;

      setState(() {
        loadingOtpOrders.remove(orderId);
      });
    }
  }

  // ============================================================
  // REFRESH
  // ============================================================

  Future<void> refreshOrders() async {
    if (mounted) {
      setState(() {
        isLoading = true;

        // Clear old OTP data.
        deliveryOtps.clear();

        otpErrors.clear();

        loadingOtpOrders.clear();
      });
    }

    await loadOrders();
  }

  // ============================================================
  // OPEN TRACKING
  // ============================================================

  void openTracking(
    Map<String, dynamic> order,
  ) {
    final orderId =
        order["_id"]?.toString() ??
        order["id"]?.toString() ??
        "";

    if (orderId.isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text(
            "orderIdNotFound".tr(),
          ),
          backgroundColor: Colors.red,
        ),
      );

      return;
    }

    final pharmacyName =
        order["pharmacyName"]?.toString() ??
        "pharmacy".tr();

    Navigator.push(
      context,
      MaterialPageRoute(
        builder: (_) =>
            MedicineOrderTrackingPage(
          orderId: orderId,
          pharmacyName: pharmacyName,
        ),
      ),
    ).then((_) {
      loadOrders();
    });
  }

  // ============================================================
  // STATUS COLOR
  // ============================================================

  Color getStatusColor(
    String status,
  ) {
    switch (status.trim().toLowerCase()) {
      case "delivered":
        return Colors.green;

      case "out for delivery":
        return Colors.orange;

      case "packed":
        return Colors.blue;

      case "accepted":
        return Colors.teal;

      case "pending":
        return Colors.grey;

      case "rejected":
      case "cancelled":
        return Colors.red;

      default:
        return Colors.grey;
    }
  }

  // ============================================================
  // CHECK OUT FOR DELIVERY
  // ============================================================

  bool isOutForDelivery(
    String status,
  ) {
    return status.trim().toLowerCase() ==
        "out for delivery";
  }

  // ============================================================
  // GET DELIVERY OTP
  // ============================================================

  String getDeliveryOtp(
    Map<String, dynamic> order,
  ) {
    final orderId =
        order["_id"]?.toString() ??
        order["id"]?.toString() ??
        "";

    if (orderId.isEmpty) {
      return "";
    }

    return deliveryOtps[orderId] ?? "";
  }

  // ============================================================
  // OTP IS LOADING
  // ============================================================

  bool isOtpLoading(
    Map<String, dynamic> order,
  ) {
    final orderId =
        order["_id"]?.toString() ??
        order["id"]?.toString() ??
        "";

    return loadingOtpOrders.contains(orderId);
  }

  // ============================================================
  // OTP ERROR
  // ============================================================

  String getOtpError(
    Map<String, dynamic> order,
  ) {
    final orderId =
        order["_id"]?.toString() ??
        order["id"]?.toString() ??
        "";

    return otpErrors[orderId] ?? "";
  }

